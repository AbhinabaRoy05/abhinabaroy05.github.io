# Builds showcase.html (the portfolio WITHOUT contact details) from index.html.
# It copies index.html and removes everything between <!-- contact:start --> and <!-- contact:end -->.
# publish.bat runs this automatically, so edit index.html only; never edit showcase.html by hand.
$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
$utf8 = New-Object System.Text.UTF8Encoding($false)
$html = [IO.File]::ReadAllText((Join-Path $root "index.html"), $utf8)

$pattern = '(?s)[ \t]*<!-- contact:start.*?<!-- contact:end -->\r?\n?'
if ($html -notmatch $pattern) { throw "Contact markers not found in index.html; showcase.html was not updated." }
$out = [regex]::Replace($html, $pattern, "")
$out = $out -replace '(?i)<!doctype html>', "<!doctype html>`n<!-- Generated from index.html by build-showcase.ps1. Do not edit this file directly. -->"

# Safety net: refuse to write the file if any contact detail slipped through.
if ($out -match '(?i)mailto:|@gmail\.com|royabhinaba') { throw "Contact details still present; showcase.html was not updated." }

[IO.File]::WriteAllText((Join-Path $root "showcase.html"), $out, $utf8)
Write-Host "showcase.html updated (no contact details)."
